// AVX-512 VBMI + VNNI dot products IQ2_XXS x Q8_K and IQ3_XXS x Q8_K (one row times one column).
//
// ggml's AVX2 kernels decode these "dictionary" formats with one scalar table load per 8 (IQ2_XXS) or 4 (IQ3_XXS)
// weights. Here every grid entry is re-coded into 2 bits (IQ2_XXS: 3 levels) or 3 bits (IQ3_XXS: 8 levels) per
// weight; the 256-entry tables of the codes stay in registers and are looked up 64 indices at a time (vpermi2b), the
// codes are spread to bytes (vpmultishiftqb) and turned into weights (vpshufb); the signs become a 64-bit mask that
// negates activations; vpdpbusd multiplies. The weights stay in the GGUF layout (no repacking in memory), so a copy
// of them on a GPU (expert cache, offload of large batches) is unaffected. Results are bit-exact with the AVX2
// kernels up to the order of the float sums. Prototype and checks: bench/moe-cpu/iq_avx512.* in JunkyYankee1/-.
//
// Included from arch/x86/quants.c when __AVX512VBMI__ and __AVX512VNNI__ are defined (CPU variants icelake, zen4,
// sapphirerapids); needs ggml-common.h (ksigns_iq2xs, blocks) and immintrin.h before.

