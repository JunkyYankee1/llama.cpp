// the levels of the codes (IQ2_XXS: 3, IQ3_XXS: 8), in each 16-byte lane for vpshufb
static const uint8_t iq512_val2[16] = { 8, 43, 25 };
static const uint8_t iq512_val3[16] = { 4, 20, 36, 12, 28, 62, 44, 52 };

// 64 lookups in a 256-entry byte table held in t[0..3]: the low 7 bits pick within a half, the top bit the half
static inline __m512i iq512_lut(const __m512i t[4], __m512i idx) {
    const __m512i a = _mm512_permutex2var_epi8(t[0], idx, t[1]);
    const __m512i b = _mm512_permutex2var_epi8(t[2], idx, t[3]);
    return _mm512_mask_blend_epi8(_mm512_movepi8_mask(idx), a, b);
}

static inline void iq512_load_lut(__m512i t[4], const uint8_t * p) {
    for (int k = 0; k < 4; k++) {
        t[k] = _mm512_loadu_si512((const void *) (p + 64 * k));
    }
}

static inline float iq512_hsum(__m512 v) {
    const __m256 a = _mm256_add_ps(_mm512_castps512_ps256(v), _mm256_castpd_ps(_mm512_extractf64x4_pd(_mm512_castps_pd(v), 1)));
    __m128       r = _mm_add_ps(_mm256_castps256_ps128(a), _mm256_extractf128_ps(a, 1));
    r              = _mm_add_ps(r, _mm_movehl_ps(r, r));
    return _mm_cvtss_f32(_mm_add_ss(r, _mm_movehdup_ps(r)));
}

// the sign masks of 8 groups of 32 weights (one 64-bit mask per 64 weights): 4 x 7 sign bits at bit offsets o, o+7,
// o+14, o+21 of each 64-bit lane of a; the 8th sign of each 8 weights makes the number of minus signs even (ksigns_iq2xs)
static inline void iq512_signs(__m512i a, int o, __m512i ks0, __m512i ks1, uint64_t m[8]) {
    static const uint8_t pack[64] = { 0,  1,  2,  3,  8,  9,  10, 11, 16, 17, 18, 19, 24, 25, 26, 27,
                                      32, 33, 34, 35, 40, 41, 42, 43, 48, 49, 50, 51, 56, 57, 58, 59 };
    const __m512i ctl = _mm512_set1_epi64((long long) ((uint64_t) o | (uint64_t) (o + 7) << 8 | (uint64_t) (o + 14) << 16 |
                                                       (uint64_t) (o + 21) << 24));
    const __m512i idx = _mm512_and_si512(_mm512_multishift_epi64_epi8(ctl, a), _mm512_set1_epi8(0x7f));
    const __m512i sg  = _mm512_permutex2var_epi8(ks0, idx, ks1);
    _mm512_storeu_si512((void *) m, _mm512_permutexvar_epi8(_mm512_loadu_si512((const void *) pack), sg));
}

// 64 weights W (2 groups of 32) times activations q8 with the sign mask m, scaled by the scales of the 2 groups
// (int32 lanes 2q, 2q+1 of sc), added to sumi
static inline __m512i iq512_acc(__m512i sumi, __m512i W, const int8_t * q8, uint64_t m, __m512i sc, int q) {
    const __m512i y  = _mm512_loadu_si512((const void *) q8);
    const __m512i ys = _mm512_mask_sub_epi8(y, (__mmask64) m, _mm512_setzero_si512(), y);
    const __m512i d  = _mm512_dpbusd_epi32(_mm512_setzero_si512(), W, ys);
    const __m512i s  = _mm512_permutexvar_epi32(
        _mm512_set_epi32(2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1,
                         2 * q, 2 * q, 2 * q, 2 * q, 2 * q, 2 * q, 2 * q, 2 * q), sc);
    return _mm512_add_epi32(sumi, _mm512_mullo_epi32(d, s));
}

// 2 * scale + 1 of 8 groups from the 4-bit scales at bit offset o of each 64-bit lane of a, as int32 lanes 0..7
static inline __m512i iq512_scales(__m512i a, int o) {
    const __m256i s = _mm512_cvtepi64_epi32(_mm512_and_si512(_mm512_srli_epi64(a, o), _mm512_set1_epi64(15)));
    return _mm512_castsi256_si512(_mm256_add_epi32(_mm256_slli_epi32(s, 1), _mm256_set1_epi32(1)));
}

static void iq512_dot_iq2_xxs(int n, float * s, const block_iq2_xxs * x, const block_q8_K * y) {
    // grid index of byte p of 8-byte lane g of the codes: entry p/2 of group g (byte 2k: low, 2k+1: high code byte)
    static const uint8_t pidx[64] = { 0,  0,  1,  1,  2,  2,  3,  3,  8,  8,  9,  9,  10, 10, 11, 11,
                                      16, 16, 17, 17, 18, 18, 19, 19, 24, 24, 25, 25, 26, 26, 27, 27,
                                      32, 32, 33, 33, 34, 34, 35, 35, 40, 40, 41, 41, 42, 42, 43, 43,
                                      48, 48, 49, 49, 50, 50, 51, 51, 56, 56, 57, 57, 58, 58, 59, 59 };
    __m512i lo[4], hi[4];
    iq512_load_lut(lo, iq512_lo2);
    iq512_load_lut(hi, iq512_hi2);
    const __m512i val = _mm512_broadcast_i32x4(_mm_loadu_si128((const __m128i *) iq512_val2));
    const __m512i ks0 = _mm512_loadu_si512((const void *) ksigns_iq2xs);
    const __m512i ks1 = _mm512_loadu_si512((const void *) (ksigns_iq2xs + 64));
    const __m512i P   = _mm512_loadu_si512((const void *) pidx);
    // weight b of an 8-byte lane L (L % 4: which quarter of the 32 weights of its group): 2 bits at 2 * (8 * (L % 4) + b)
    const __m512i ctlw = _mm512_set_epi64(0x3e3c3a3836343230LL, 0x2e2c2a2826242220LL, 0x1e1c1a1816141210LL, 0x0e0c0a0806040200LL,
                                          0x3e3c3a3836343230LL, 0x2e2c2a2826242220LL, 0x1e1c1a1816141210LL, 0x0e0c0a0806040200LL);
    const __m512i m3   = _mm512_set1_epi8(3);
    __m512 acc = _mm512_setzero_ps();
    for (int i = 0; i < n / QK_K; ++i) {
        // 8 groups of 32 weights, 8 bytes each: 4 grid indices, then 4 x 7 sign bits and a 4-bit scale
        const __m512i Q  = _mm512_loadu_si512((const void *) x[i].qs);
        const __m512i ix = _mm512_permutexvar_epi8(P, Q);
        const __m512i C  = _mm512_mask_blend_epi8((__mmask64) 0xAAAAAAAAAAAAAAAAULL, iq512_lut(lo, ix), iq512_lut(hi, ix));
        uint64_t      sm[8];
        iq512_signs(Q, 32, ks0, ks1, sm);
        const __m512i sc   = iq512_scales(Q, 60);
        __m512i       sumi = _mm512_setzero_si512();
        for (int q = 0; q < 4; q++) {
            const __m512i g = _mm512_permutexvar_epi64(_mm512_set_epi64(2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q + 1, 2 * q, 2 * q, 2 * q, 2 * q), C);
            const __m512i W = _mm512_shuffle_epi8(val, _mm512_and_si512(_mm512_multishift_epi64_epi8(ctlw, g), m3));
            sumi = iq512_acc(sumi, W, y[i].qs + 64 * q, sm[q], sc, q);
        }
        acc = _mm512_fmadd_ps(_mm512_set1_ps(GGML_CPU_FP16_TO_FP32(x[i].d) * y[i].d), _mm512_cvtepi32_ps(sumi), acc);
    }
    *s = 0.125f * iq512_hsum(acc);
}

